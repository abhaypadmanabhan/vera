#!/usr/bin/env node
/**
 * Reads data/demo-business.csv and writes data/demo.ts so the app import
 * surface can never drift from the CSV on disk.
 *
 * Usage: node scripts/build-demo-data.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = join(root, "data", "demo-business.csv");
const outPath = join(root, "data", "demo.ts");

const csv = readFileSync(csvPath, "utf8");

/** One-click demo prompts — must match the dataset story in data/README.md. */
const questions = [
  "What was EMEA's gross margin percentage in Q3 2025?",
  "By what percentage did company-wide revenue grow from Q2 2025 to Q3 2025?",
  "What was EMEA Core's gross margin percentage in Q3 2025?",
];

function asTsStringLiteral(value) {
  return JSON.stringify(value);
}

const body = `/**
 * Auto-generated by scripts/build-demo-data.mjs — do not edit by hand.
 * Re-run: node scripts/build-demo-data.mjs
 */

export const DEMO_FILENAME: string = "demo-business.csv";

export const DEMO_CSV: string = ${asTsStringLiteral(csv)};

export const DEMO_QUESTIONS: string[] = ${asTsStringLiteral(questions)};
`;

writeFileSync(outPath, body, "utf8");
console.log(`Wrote ${outPath} (${csv.length} CSV chars, ${questions.length} questions)`);
